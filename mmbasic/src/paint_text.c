/* Longest string the tool holds: comfortably past the 608-pixel canvas, and a
 * small fixed buffer. */
#define PT_TEXT_MAX 96

/* ---- editing state ----------------------------------------------------- */

static int s_active;		/* a caret is placed and the buffer is open */
static int s_x, s_y;		/* caret origin, canvas coords */
static int s_color;		/* palette index the text is drawn with */
static int s_len;
static unsigned char s_buf[PT_TEXT_MAX];
static int s_have_base;		/* PT.scratch holds the pre-text canvas */

/* ---- drawing ----------------------------------------------------------- */

static void text_glyph(int x0, int y0, unsigned ch, int color)
{
	const unsigned char *g = s_font + (size_t)(ch & 255u) * PT_TEXT_FH;
	int row, col;

	for (row = 0; row < PT_TEXT_FH; row++)
	{
		unsigned bits = g[row];

		for (col = 0; col < PT_TEXT_FW; col++)
			if (bits & (0x80u >> col))
				pt_canvas_set(x0 + col, y0 + row, color);
	}
}

static void text_caret(int x, int y, int color)
{
	int row;

	for (row = 0; row < PT_TEXT_FH; row++)
		pt_canvas_set(x, y + row, color);
}

/* Redraw the whole live string; the caret trails the last glyph. */
static void text_draw(int caret)
{
	int i;

	for (i = 0; i < s_len; i++)
		text_glyph(s_x + i * PT_TEXT_FW, s_y, s_buf[i], s_color);
	if (caret)
		text_caret(s_x + s_len * PT_TEXT_FW, s_y, s_color);
}

/* ---- preview / commit -------------------------------------------------- */

static void text_capture(void)
{
	if (PT.scratch && PT.canvas && !s_have_base)
	{
		memcpy(PT.scratch, PT.canvas, (size_t)PT.width * PT.height);
		s_have_base = 1;
		PT.scratch_valid = 1;
	}
}

static void text_restore(void)
{
	if (PT.scratch && PT.canvas && s_have_base)
		memcpy(PT.canvas, PT.scratch, (size_t)PT.width * PT.height);
}

static void text_refresh(void)
{
	text_capture();
	text_restore();
	text_draw(1);
	pt_request_redraw();
}

static void text_finish(void)
{
	s_active = 0;
	s_len = 0;
	s_have_base = 0;
	if (PT.scratch)
		PT.scratch_valid = 0;
}

/* ---- public hooks ------------------------------------------------------ */

void pt_text_init(void)
{
	s_active = 0;
	s_len = 0;
	s_have_base = 0;
	s_x = 0;
	s_y = 0;
	s_color = PT.fg;
}

int pt_text_active(void)
{
	return s_active;
}

/* Tool hook (called from paint_tools.c): a canvas click drops the caret and
 * opens the buffer. Re-clicking commits whatever is open first. */
void pt_text_begin(int cx, int cy, int button)
{
	if (!PT.canvas || PT.width <= 0 || PT.height <= 0)
		return;
	if (s_active)
		pt_text_commit();
	if (s_have_base)
		text_restore();

	s_x = cx;
	s_y = cy;
	s_color = (button == PT_BTN_RIGHT) ? PT.bg : PT.fg;
	s_len = 0;
	s_active = 1;
	text_capture();
	text_draw(1);
	pt_request_redraw();
}

void pt_text_commit(void)
{
	if (!s_active)
		return;

	/* Rewind to the pre-text canvas, then record exactly one history step
	 * before baking the string in. */
	text_restore();
	if (s_len > 0)
	{
		pt_undo_push();
		text_draw(0);
	}
	text_finish();
	pt_request_redraw();
}

void pt_text_cancel(void)
{
	if (!s_active)
		return;

	text_restore();
	text_finish();
	pt_request_redraw();
}

int pt_text_key(int key)
{
	unsigned char c = (unsigned char)key;

	if (!s_active)
		return 0;

	switch (c)
	{
	case 13:			/* Enter: commit */
	case 10:
		pt_text_commit();
		return 1;
	case 27:			/* Esc: cancel */
		pt_text_cancel();
		return 1;
	case 8:				/* Backspace */
	case 127:
		if (s_len > 0)
			s_len--;
		text_refresh();
		return 1;
	default:
		if (c >= 32 && s_len < PT_TEXT_MAX)
		{
			s_buf[s_len++] = c;
			text_refresh();
		}
		return 1;		/* swallow other keys while editing */
	}
}
