/* Tool hook (called from paint_tools.c): a canvas click drops the caret and
 * opens the buffer. Re-clicking commits whatever is open first. */
void pt_text_begin(int cx, int cy, int button)
{
	if (!PT.canvas || PT.width <= 0 || PT.height <= 0)
		return;
	if (s_active)
		pt_text_commit();
	if (s_have_base)
		text_restore();
	s_picker = 0;

	s_x = cx;
	s_y = cy;
	s_color = (button == PT_BTN_RIGHT) ? PT.bg : PT.fg;
	s_len = 0;
	s_active = 1;
	text_capture();
	text_draw(1);
	pt_request_redraw();
}

void pt_text_commit(void)
{
	if (!s_active)
		return;

	/* Rewind to the pre-text canvas, then record exactly one history step
	 * before baking the string in. */
	text_restore();
	if (s_len > 0)
	{
		pt_undo_push();
		text_draw(0);
	}
	text_finish();
	pt_request_redraw();
}

void pt_text_cancel(void)
{
	if (!s_active)
		return;

	text_restore();
	text_finish();
	pt_request_redraw();
}

int pt_text_key(int key)
{
	unsigned char c = (unsigned char)key;

	if (!s_active)
		return 0;

	if (s_picker)
	{
		int rows = s_cat_n + 1;

		if (c == 27)			/* Esc: close the list */
		{
			s_picker = 0;
			text_refresh();
		}
		else if (c == 13 || c == 10)	/* Enter: choose */
		{
			if (s_pick_sel <= 0)
				pt_text_font_builtin();
			else
				pt_text_font_load(s_pick_sel - 1);
			s_picker = 0;
			text_refresh();
		}
		else if (c == 'n' || c == 'j' || c == '2')
		{
			if (s_pick_sel + 1 < rows)
				s_pick_sel++;
			text_refresh();
		}
		else if (c == 'p' || c == 'k' || c == '8')
		{
			if (s_pick_sel > 0)
				s_pick_sel--;
			text_refresh();
		}
		return 1;
	}

	switch (c)
	{
	case 6:				/* Ctrl+F: choose a font */
		pt_text_font_picker_open();
		return 1;
	case 13:			/* Enter: commit */
	case 10:
		pt_text_commit();
		return 1;
	case 27:			/* Esc: cancel */
		pt_text_cancel();
		return 1;
	case 8:				/* Backspace */
	case 127:
		if (s_len > 0)
			s_len--;
		text_refresh();
		return 1;
	default:
		if (c >= 32 && s_len < PT_TEXT_MAX)
		{
			s_buf[s_len++] = c;
			text_refresh();
		}
		return 1;		/* swallow other keys while editing */
	}
}
