/*
 * PAINT - text tool (#642).
 *
 * Click the canvas with the TEXT tool to drop a caret, then type. Each
 * character is drawn from the built-in IBM CP437 8x8 font at 8-pixel steps,
 * using the foreground index -- or the background index when the caret was
 * placed with the right button. Backspace edits the buffer; Enter bakes the
 * string into the canvas as one image operation (a single pt_undo_push());
 * Esc drops it. Nothing stays editable after the commit: the result is just
 * canvas pixels, like any other tool.
 *
 * The live string is previewed over PT.scratch. Every keystroke restores the
 * backed-up canvas and redraws the buffer (plus a caret), so cancelling puts
 * the original pixels back and the commit can snapshot an untouched canvas
 * for the single undo step.
 */
